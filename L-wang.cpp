/*
小王加水】】】‘

问题描述
小王和他的好朋友一起玩游戏，游戏内容是往一个容量为 N 升的容器中加水看谁先加满，每次可以加 1 升或者 2 升的水，小王先加，请问小王是否有机会赢得本次游戏，可以则输出 YES,否则输出 NO。

输入格式
输入一个正整数 N。

输出格式
输出 YES 或者 NO。

样例输入
5

样例输出
YES

评测数据规模
对于 30% 的评测数据，0<N<100。

对于所有评测数据，
0<N<10^5。
*/
#include <iostream>
using namespace std;
int main()
{
	int n;
	cin >> n;
	cout << (n % 3 ? "YES" : "NO") << endl;

	return 0;
}
