/*】】】】[
妮妮的奇妙烹饪之旅

问题描述
妮妮是一位热爱烹饪的小女孩，她发现烹饪中有一种神秘的规律。
每次烹饪，她都会选择一个数字 N 作为烹饪的起始步骤。
如果数字是奇数，她就会在烹饪中加一种新的食材；
如果是偶数，那么她就会将食材减半。
妮妮会重复这个过程，直到最后步骤变为 1，也就是只剩下一种食材。

请你帮助妮妮，根据她选择的起始步骤 N，计算出她完成烹饪需要的步骤数。

输入格式
输入的第一行包含一个整数 N（1≤N≤10^9），表示妮妮选择的烹饪起始步骤。

输出格式
输出一行，表示妮妮完成烹饪需要的步骤数。

样例输入
10

样例输出
6
*/
#include <iostream>
using namespace std;
int main()
{
    int n, i = 0;
    cin >> n;
    while (n != 1)
    {
        if (n % 2)
            n++;
        else
            n /= 2;
        i++;
    }
    cout << i << endl;

    return 0;
}
