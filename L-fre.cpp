/*][=]]
散养的小猪

问题描述
在一个农场里养了很多头的小猪，这些小猪有些被栅栏围了起来，有些则散养在了栅栏的外面，假设栅栏用小写字母 r 表示，小猪用字母 p 表示，一对 r 之间的 p 表示这些小猪被围在了栅栏里（每 两个 连续的 r 为一对，第一个和第二个 r 为一对，第三个和第四个 r 为一对，以此类推），问散养在外面的小猪数量是多少？

输入格式
输入一行只包含小写字母 r 和 p 的字符串。

注意：每个测试数据中，字母 r 有偶数个，且字符串长度 ∈[1,10^5]。

输出格式
输出一行，这一行只包含一个整数，表示答案。

样例输入1
prpprpprpr

样例输出1
3

样例输入2
ppp

样例输出2
3

说明/提示
样例 1 中，第一对 r 之间圈养了 2 头小猪，第二对 r 之间圈养了 1 头小猪。
因此，有 3 头小猪散养在外。

样例 2 中，因为没有栅栏，因此 3 头小猪都散养在外。
*/
#include <iostream>
#include <string>
using namespace std;
int main()
{
    int m = 0;
    bool b = 1;
    string s;
    getline(cin, s);
    for (char c : s)
    {
        if (c == 'r')
            b = !b;
        else if (c == 'p')
            m += b;
    }
    cout << m << endl;

    return 0;
}
