/*】】】
鸡哥的魔法石

问题描述
在鸡哥的家乡，有个传说，说是有一块神奇的魔法石，这块石头有个奇特的属性，它可以吸收一个整数 X 的能量。
每次吸收时，它会将这个数字的所有数字之和从 X 中减去，并继续吸收新结果的能量，直到吸收的能量等于 0。
鸡哥被这个奇妙的现象所吸引，他想知道，如果他有一个整数 X，魔法石需要吸收几次能量才能将这个数字消耗到 0。

你能帮鸡哥解决这个问题吗？

输入格式
输入的第一行包含一个整数 X （0≤X≤10^4）。

输出格式
输出的第一行应包含一个整数，代表魔法石需要吸收的次数。

样例输入
24

样例输出
4
*/
#include <iostream>
using namespace std;
int main()
{
    int n, m, k = 1;
    cin >> n;
    while (n)
    {
        m = n;
        while (m)
            n -= m % 10, m /= 10;
        k++;
    }
    cout << k << endl;

    return 0;
}
