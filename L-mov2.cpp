/*]]]\
搬家

问题描述
小蓝要搬家，他将家里的物品打包成了同等质量的包裹，每个包裹重量都是 W 千克。
搬家所用的货车一次最多拉 N 千克的包裹。

请你帮助小蓝计算，货车需要运几趟才能帮小蓝搬完家。

输入格式
从标准输入读取两个整数 N 和 W（1≤N,W≤2×10^5），分别代表货车的货运量和每个包裹的重量。

输出格式
输出一个整数，表示货车最多可以承载多少个包裹。

样例输入
100
5

样例输出
20

在这个样例中，货车的承载量是 100 千克，每个包裹的重量是 5 千克，所以货车最多可以装 20 个包裹。
*/
#include <iostream>
using namespace std;
int main()
{
	int n, m;
	cin >> n >> m;
	cout << n / m << endl;

	return 0;
}
