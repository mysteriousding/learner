/*】】】】、
时长计算

问题描述
小蓝将自己的车停在路边，在同一天将车开走。
给定停车时间和开走时间，请问小蓝停了多长时间?

输入格式
输入两行，第一行包含停车时间，第二行包含开走时间。

每个时间的格式为 HH:MM:SS，其中 HH 表示时，值为 0 到 23 的整数，如果小于 10 用 0 补齐两 位；
MM 和 SS 分别表示分和秒，值为 0 到 59 的整数，小于 10 时用 0 补齐两位。

输出格式
输出总共停车的时间，格式为 HH:MM:SS。

样例输入
08:58:10

17:20:31

样例输出
08: 22: 21
*/
#include <iostream>
using namespace std;
int main()
{
    int a, b, c, x, y, z;
    char h;
    cin >> a >> h >> b >> h >> c >> x >> h >> y >> h >> z;
    z -= c, y -= b, x -= a;
    if (z < 0)
        z += 60, y--;
    if (y < 0)
        y += 60, x--;
    printf("%02d:%02d:%02d", x, y, z);

    return 0;
}
