/*】】】】】
花园中的安全选择

问题描述
可可来到一个花园，花园内有 N 种不同的花朵。
每种花朵都有一定数量的花瓣，其中一些花瓣会引起过敏。
现在可可需要从每种花朵中随机摘一片花瓣，她想要选择最不可能引起过敏的花朵。
请帮助可可计算出哪种花朵最安全。

输入格式
第一行包含一个整数 N。

接下来的 N 行，每行包含两个整数 ti 和 pi ，分别代表第 i 种花朵的花瓣总数和会引起过敏的花瓣数。

输出格式
输出最安全的花朵的索引。如果有多个答案，则输出索引最小的那个。

样例输入
3
2 1
3 2
4 2

样例输出
1

评测数据规模
1≤N≤100
1≤pi≤ti≤100
*/
#include <iostream>
using namespace std;
int main()
{
    int n, k;
    double a, b, c = 1;
    cin >> n;
    for (int i = 0; i < n; i++)
    {
        cin >> a >> b;
        b /= a * 1.0;
        if (b < c)
            c = b, k = i + 1;
    }
    cout << k << endl;

    return 0;
}
