/*】】】】】
颠倒数的和

来源
Central Europe 1998 (ZOJ2001, POJ1504)

题目描述
颠倒数是由阿拉伯数字组成的，但其数字的顺序颠倒了。
即原来的第一位数字在颠倒数中变为最后一位数字。
注意所有前导的0被省略。
也就是，如果一个数以0结尾，在颠倒数中0将丢失。
(如1200颠倒后得到21)。
这样颠倒数将不可能有后导的0。

编写程序，将两个颠倒数相加，并输出它们的颠倒和。
当然，结果不是唯一的，因为每一个颠倒数都可能是多个数的颠倒形式，例如，颠倒数21可以是12、120或1200等等数的颠倒。
因此，假定颠倒时没有0丢失，这样颠倒数21，在颠倒前是12。

输入描述
输入文件中包含N个测试数据。
输入文件的第1行为正整数N。
接下来是N个测试数据。
每个测试数据占一行，为两个正整数，用空格隔开。
这就是需要求和的两个颠倒数。

输出描述
对每个测试数据，输出一行，为一个整数，表示两个颠倒数的和（注意它们的和也是颠倒数），忽略所有的前导0。

样例输入
2
24 1
305 794

样例输出
34
1
*/
#include <iostream>
using namespace std;
inline int cl(int x)
{
    int y = 0;
    while (x)
        y *= 10, y += x % 10, x /= 10;
    return y;
}
int main()
{
    int n, a, b, c;
    cin >> n;
    for (int i = 0; i < n; i++)
    {
        cin >> a >> b;
        c = cl(a);
        c += cl(b);
        cout << cl(c) << endl;
    }

    return 0;
}
