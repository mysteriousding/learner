/*】】】【
车站

题目描述
火车从始发站（称为第 1 站）开出，在始发站上车的人数为 a，然后到达第 2 站，在第 2 站有人上、下车，但上、下车的人数相同，因此在第 2 站开出时（即在到达第 3 站之前）车上的人数保持为 a 人。
从第 3 站起（包括第 3 站）上、下车的人数有一定规律：
上车的人数都是前两站上车人数之和，而下车人数等于上一站上车人数，一直到终点站的前一站（第 n−1 站），都满足此规律。
现给出的条件是：
共有 N 个车站，始发站上车的人数为 a，最后一站下车的人数是 m（全部下车）。
试问x站开出时车上的人数是多少？

输入描述
输入只有一行四个整数，分别表示始发站上车人数 a，车站数 n，终点站下车人数 m 和所求的站点编号 x。

其中,1≤a≤20，1≤x≤n≤20，1≤m≤2×10^4。

输出描述
输出一行一个整数表示答案：
从 x 站开出时车上的人数。

输入输出样例
示例 1
输入
5 7 32 4

输出
13
*/
#include <iostream>
using namespace std;
int main()
{
    int q, n, m, x, h, a[21] = { 0,1,1 }, b[21] = { 0 }, c[21] = { 1,0,1 }, d[21] = { 0,1,1 };
    cin >> q >> n >> m >> x;

    if (x == n)
        cout << m << endl;
    else if (x < 3)
        cout << q << endl;
    else
    {
        for (int i = 3; i < n; i++)
            c[i] = c[i - 1] + c[i - 2], d[i] = d[i - 1] + d[i - 2], a[i] = a[i - 1] + c[i - 3], b[i] = b[i - 1] + d[i - 3];
        h = (m - q * a[n - 1]) / b[n - 1];
        cout << q * a[x] + h * b[x] << endl;
    }

    return 0;
}
