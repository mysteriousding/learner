/*
第P页

问题描述
小蓝要写一个网页显示一些商品。

商品总共有 t 个，按顺序由 1 到 t 编号，每页显示 a 个，请问第 p 页显示的最小和最大编号是多 少?

输入格式
输入一行包含三个整数 t、a,p，相邻整数之间用一个空格分隔。

输出格式
输出一行包含两个整数，分别表示最小和最大编号。

样例输入
31 10 3

样例输出
21 30

样例输入
31 10 4

样例输出
31 31

评测用例规模与约定
对于所有评测用例，1<=t<=1000,1<=a<=100,1<=p 。
保证第 p 页至少显示一个商品。
*/
#include <iostream>
using namespace std;
int main()
{
	int a, b, c;
	cin >> a >> b >> c;
	cout << b * c - b + 1 << ' ' << (b * c <= a ? b * c : a) << endl;

	return 0;
}